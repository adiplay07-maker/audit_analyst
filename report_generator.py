"""
report_generator.py
-------------------
Generates formatted audit summary reports in HTML and plain text.
"""

import pandas as pd
from datetime import datetime
from pathlib import Path


class ReportGenerator:
    """Generates audit reports from analysis results."""

    def __init__(self, output_dir: str = "reports"):
        self.output_dir = Path(output_dir)
        self.output_dir.mkdir(exist_ok=True)

    def generate_html(
        self,
        risk_df: pd.DataFrame,
        anomaly_df: pd.DataFrame,
        transactions: pd.DataFrame,
        report_period: str = "FY 2024",
    ) -> str:
        """Generate a styled HTML audit report."""

        timestamp = datetime.now().strftime("%d %b %Y, %H:%M")
        total_txns = len(transactions)
        total_amount = transactions["amount"].sum()
        flagged = len(anomaly_df)
        flag_rate = round(flagged / total_txns * 100, 2)

        critical = risk_df[risk_df["risk_level"] == "Critical"]
        high = risk_df[risk_df["risk_level"] == "High"]

        risk_rows = ""
        for _, row in risk_df.iterrows():
            color = {"Low": "#22c55e", "Medium": "#eab308",
                     "High": "#f97316", "Critical": "#ef4444"}.get(row["risk_level"], "#888")
            risk_rows += f"""
            <tr>
                <td>{row['entity']}</td>
                <td>{row['transaction_count']}</td>
                <td>₹{row['avg_amount']:,.0f}</td>
                <td>{row['anomaly_rate_%']}%</td>
                <td style="color:{color}; font-weight:600">{row['risk_icon']} {row['risk_level']}</td>
                <td><b>{row['risk_score']}</b></td>
            </tr>"""

        anomaly_rows = ""
        for _, row in anomaly_df.head(10).iterrows():
            anomaly_rows += f"""
            <tr>
                <td>{row.get('transaction_id','—')}</td>
                <td>{str(row.get('date','—'))[:10]}</td>
                <td>{row.get('department','—')}</td>
                <td>{row.get('vendor','—')}</td>
                <td style="color:#ef4444; font-weight:600">₹{row.get('amount',0):,.2f}</td>
            </tr>"""

        html = f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8"/>
<title>Audit Analytics Report – {report_period}</title>
<style>
  body {{ font-family: 'Segoe UI', Arial, sans-serif; background:#f8fafc; color:#1e293b; margin:0; padding:2rem; }}
  h1   {{ color:#1e3a5f; border-bottom:3px solid #1e3a5f; padding-bottom:.5rem; }}
  h2   {{ color:#1e3a5f; margin-top:2rem; }}
  .meta {{ color:#64748b; font-size:.9rem; margin-bottom:2rem; }}
  .kpi-row {{ display:flex; gap:1rem; flex-wrap:wrap; margin:1.5rem 0; }}
  .kpi {{ background:#fff; border-radius:10px; padding:1.2rem 2rem; box-shadow:0 2px 8px rgba(0,0,0,.08); flex:1; min-width:150px; }}
  .kpi .value {{ font-size:2rem; font-weight:700; color:#1e3a5f; }}
  .kpi .label {{ font-size:.85rem; color:#64748b; margin-top:.2rem; }}
  table {{ width:100%; border-collapse:collapse; background:#fff; border-radius:8px; overflow:hidden; box-shadow:0 2px 8px rgba(0,0,0,.06); }}
  th {{ background:#1e3a5f; color:#fff; padding:.75rem 1rem; text-align:left; font-size:.85rem; }}
  td {{ padding:.65rem 1rem; border-bottom:1px solid #e2e8f0; font-size:.9rem; }}
  tr:hover td {{ background:#f1f5f9; }}
  .footer {{ margin-top:3rem; color:#94a3b8; font-size:.8rem; border-top:1px solid #e2e8f0; padding-top:1rem; }}
</style>
</head>
<body>
<h1>📊 Internal Audit Analytics Report</h1>
<div class="meta">Report Period: {report_period} &nbsp;|&nbsp; Generated: {timestamp} &nbsp;|&nbsp; Classification: Internal</div>

<h2>Executive Summary</h2>
<div class="kpi-row">
  <div class="kpi"><div class="value">{total_txns:,}</div><div class="label">Total Transactions</div></div>
  <div class="kpi"><div class="value">₹{total_amount/1e6:.1f}M</div><div class="label">Total Amount</div></div>
  <div class="kpi"><div class="value">{flagged}</div><div class="label">Flagged Anomalies</div></div>
  <div class="kpi"><div class="value">{flag_rate}%</div><div class="label">Flag Rate</div></div>
  <div class="kpi"><div class="value">{len(critical)}</div><div class="label">Critical Risk Units</div></div>
  <div class="kpi"><div class="value">{len(high)}</div><div class="label">High Risk Units</div></div>
</div>

<h2>Risk Matrix by Department</h2>
<table>
  <thead><tr><th>Department</th><th>Transactions</th><th>Avg Amount</th><th>Anomaly Rate</th><th>Risk Level</th><th>Score (0–100)</th></tr></thead>
  <tbody>{risk_rows}</tbody>
</table>

<h2>Top 10 Flagged Transactions</h2>
<table>
  <thead><tr><th>Transaction ID</th><th>Date</th><th>Department</th><th>Vendor</th><th>Amount</th></tr></thead>
  <tbody>{anomaly_rows}</tbody>
</table>

<div class="footer">This report was auto-generated by the Audit Analytics Pipeline. For queries, contact the Internal Audit team.</div>
</body></html>"""

        report_path = self.output_dir / f"audit_report_{datetime.now().strftime('%Y%m%d_%H%M%S')}.html"
        report_path.write_text(html, encoding="utf-8")
        print(f"[✓] HTML report saved to: {report_path}")
        return str(report_path)

    def generate_text_summary(self, risk_df: pd.DataFrame, anomaly_count: int, total: int) -> str:
        """Print a concise text summary to console."""
        lines = [
            "=" * 60,
            "   AUDIT ANALYTICS — SUMMARY",
            "=" * 60,
            f"  Total transactions analysed : {total}",
            f"  Anomalies flagged           : {anomaly_count} ({round(anomaly_count/total*100,1)}%)",
            "",
            "  RISK LEVELS BY DEPARTMENT:",
        ]
        for _, row in risk_df.iterrows():
            lines.append(f"  {row['risk_icon']}  {row['entity']:<15} Score: {row['risk_score']:.1f}  [{row['risk_level']}]")
        lines.append("=" * 60)
        summary = "\n".join(lines)
        print(summary)
        return summary
